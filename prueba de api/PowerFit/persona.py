# Define una clase mínima usada como borrador del modelo Persona.
class Persona:
    # Guarda el RUT de la persona.
    rut: str
    # Guarda el nombre de la persona.
    nombre: str
    # Guarda el apellido paterno.
    apellidoPaterno: str
    # Guarda el apellido materno.
    apellidoMaterno: str
    # Guarda el teléfono de contacto.
    telefono: str
    # Guarda el correo electrónico.
    correoElectronico: str
